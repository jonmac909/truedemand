import type { MarketingPlanExportData, ExportMetadata } from './types';

/**
 * Convert blueprint GTM data to standalone Marketing Plan Markdown.
 *
 * This is a DERIVED export - marketing plans are not stored separately.
 * Data is extracted from blueprint.gtm_recommendations + related context.
 *
 * @param data - Marketing plan export data (derived from blueprint)
 * @param metadata - Export metadata
 * @returns Markdown string
 */
export function marketingPlanToMarkdown(
  data: MarketingPlanExportData,
  metadata: ExportMetadata
): string {
  const sections: string[] = [];

  // Header
  sections.push(generateHeader(data, metadata));

  // Product Overview
  sections.push(generateProductOverview(data));

  // Market Context
  sections.push(generateMarketContext(data));

  // Positioning
  sections.push(generatePositioning(data));

  // GTM Recommendations (main content)
  sections.push(generateGTMRecommendations(data));

  // Target Audience
  sections.push(generateTargetAudience(data));

  // Footer
  sections.push(generateFooter(metadata));

  return sections.join('\n\n---\n\n');
}

function generateHeader(data: MarketingPlanExportData, metadata: ExportMetadata): string {
  return `# Marketing Plan: ${data.product_title}

**Generated**: ${new Date(metadata.generated_at).toLocaleString('en-US', {
    dateStyle: 'long',
    timeStyle: 'short',
  })}
**Market**: ${data.market_name}
**Validation Score**: ${data.validation_score}/100

> ${data.value_proposition}`;
}

function generateProductOverview(data: MarketingPlanExportData): string {
  return `## Product Overview

**Product Name**: ${data.product_title}

**Value Proposition**: ${data.value_proposition}

**Target Customer**: ${data.target_persona}

**Market Opportunity**: This marketing plan is based on validated market demand with a ${data.validation_score}/100 validation score across multiple signals (search trends, social proof, competition analysis, and financial indicators).`;
}

function generateMarketContext(data: MarketingPlanExportData): string {
  return `## Market Context

**Target Market**: ${data.market_name}

**Validation Score**: ${data.validation_score}/100

${
    data.validation_score >= 70
      ? '**Assessment**: Strong validation signals indicate a high-demand market with clear opportunities for differentiation.'
      : data.validation_score >= 40
        ? '**Assessment**: Moderate validation signals suggest promising potential with careful positioning and customer targeting.'
        : '**Assessment**: Weak validation signals recommend additional market research before significant marketing investment.'
  }

This marketing plan is built on comprehensive market analysis including search trends, social media engagement, competitive landscape assessment, and financial viability research.`;
}

function generatePositioning(data: MarketingPlanExportData): string {
  return data.positioning_strategy;
}

function generateGTMRecommendations(data: MarketingPlanExportData): string {
  return data.gtm_recommendations;
}

function generateTargetAudience(data: MarketingPlanExportData): string {
  // Extract target audience section from target_market_analysis
  // This is a simplified extraction - the full analysis is in the blueprint
  return `## Target Audience Summary

**Primary Persona**: ${data.target_persona}

For detailed target market segmentation, demographics, psychographics, and buying behavior analysis, refer to the full implementation blueprint.

**Key Insights**:
- Focus on early adopters for initial traction
- Leverage community-led growth strategies
- Prioritize customer feedback and rapid iteration
- Build case studies and testimonials for social proof`;
}

function generateFooter(metadata: ExportMetadata): string {
  return `## About This Document

**Export Details:**
- Generated: ${new Date(metadata.generated_at).toLocaleString('en-US', { dateStyle: 'long', timeStyle: 'short' })}
- Export Type: Marketing Plan (derived from Implementation Blueprint)
- Export Version: ${metadata.export_version}
- App Version: ${metadata.app_version}

**Note:** This marketing plan is derived from the comprehensive implementation blueprint. For complete feature roadmap, technical requirements, and detailed risk assessment, refer to the full blueprint export.

**Disclaimer:**
This marketing plan is based on automated market analysis and should be validated with customer interviews, A/B testing, and iterative refinement based on real-world feedback.

---

*Generated by [TrueDemand](https://truedemand.app) — Market Validation for Product Builders*`;
}
